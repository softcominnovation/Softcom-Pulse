import { test, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { adminFixture } from "../fixtures/admin";
import { signIn } from "../fixtures/infrastructure";
import { notificationFixture, notificationFixtureState, addNotification } from "../fixtures/notifications";
import { notificationDay } from "../../lib/notifications/history-range";

for (const viewport of [{ width: 390, height: 844 }, { width: 1366, height: 768 }]) test(`notification history defaults to today and keeps dates across pagination at ${viewport.width}px`, async ({ page }) => {
  await page.setViewportSize(viewport);
  const today = notificationDay(), midnight = Date.parse(`${today}T03:00:00Z`), yesterday = notificationDay(midnight - 86400000), tomorrow = notificationDay(midnight + 86400000);
  const state = notificationFixtureState(); state.historyPageSize = 1;
  const old = addNotification(state); old.displayName = "Registro de ontem"; old.createdAt = new Date(midnight - 1000).toISOString();
  const current = addNotification(state); current.displayName = "Registro de hoje";
  await adminFixture(page); await notificationFixture(page, state); await signIn(page);
  await page.getByRole("button", { name: /^Notificações:/ }).click();
  const sheet = page.getByRole("dialog", { name: "Notificações", exact: true });
  await expect(sheet.getByText("Registro de ontem", { exact: true })).toBeVisible();
  await expect(sheet.getByLabel("Data inicial", { exact: true })).toHaveCount(0);
  await sheet.getByRole("button", { name: "Histórico", exact: true }).click();
  const from = sheet.getByLabel("Data inicial", { exact: true }), to = sheet.getByLabel("Data final (opcional)", { exact: true });
  await expect(from).toHaveValue(today); await expect(to).toHaveValue("");
  await expect(from).toHaveAttribute("max",today); await expect(to).toHaveAttribute("max",today);
  await expect(sheet.getByText("Registro de hoje", { exact: true })).toBeVisible();
  await expect(sheet.getByText("Registro de ontem", { exact: true })).toHaveCount(0);
  await from.fill(yesterday); await to.fill(today);
  await sheet.getByRole("button", { name: "Filtrar período", exact: true }).click();
  await expect(sheet.getByRole("button", { name: "Carregar mais", exact: true })).toBeVisible();
  await sheet.getByRole("button", { name: "Carregar mais", exact: true }).click();
  await expect(sheet.getByText("Registro de ontem", { exact: true })).toBeVisible();
  expect(state.listQueries.at(-1)).toMatchObject({ path: "/api/monitoring/notifications/history", from: yesterday, to: today, cursor: "1" });
  await to.fill(""); await sheet.getByRole("button", { name: "Filtrar período", exact: true }).click();
  await expect(sheet.getByText("Registro de ontem", { exact: true })).toBeVisible();
  await expect(sheet.getByText("Registro de hoje", { exact: true })).toHaveCount(0);
  const requests = state.listQueries.length;
  await from.fill(tomorrow); await sheet.getByRole("button", { name: "Filtrar período", exact: true }).click();
  await expect(sheet.getByRole("alert")).toContainText("não pode estar no futuro");
  expect(state.listQueries).toHaveLength(requests);
  await from.fill(""); await sheet.getByRole("button", { name: "Filtrar período", exact: true }).click();
  await expect(sheet.getByRole("alert")).toContainText("data inicial válida");
  await sheet.getByRole("button", { name: "Hoje", exact: true }).click();
  await expect(from).toHaveValue(today); await expect(to).toHaveValue("");
  await expect(sheet.getByText("Registro de hoje", { exact: true })).toBeVisible();
  expect(await sheet.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await mkdir(".cache/screenshots", { recursive: true });
  await sheet.screenshot({ path: `.cache/screenshots/notification-history-${viewport.width}.png` });
  await sheet.getByRole("button", { name: "Incidentes atuais", exact: true }).click();
  await expect(from).toHaveCount(0);
  await expect.poll(() => state.listQueries.at(-1)?.path).toBe("/api/monitoring/notifications/incidents");
  expect(state.listQueries.at(-1)).toMatchObject({ from: null, to: null });
  await sheet.getByRole("button", { name: "Não lidas", exact: true }).click();
  await expect(sheet.getByText("Registro de ontem", { exact: true })).toBeVisible();
  expect(state.listQueries.at(-1)).toMatchObject({ read: "unread", from: null, to: null });
});
