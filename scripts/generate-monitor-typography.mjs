// Generate literal font sizes for older TVs from the existing stylesheet.
// No runtime CSS parser, CSS variables, new endpoint or DOM mutation is needed.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

export async function generateMonitorTypography() {
  const css = await readFile(new URL('../public/monitor-compat.css', import.meta.url), 'utf8');
  const rules = [];
  postcss.parse(css).walkRules(rule => {
    let size;
    rule.walkDecls(decl => {
      if (decl.prop === 'font-size' && /^\d+(?:\.\d+)?px$/.test(decl.value)) size = parseFloat(decl.value);
      if (decl.prop === 'font') {
        const match = decl.value.match(/(?:^|\s)(\d+(?:\.\d+)?)px(?:[\s/]|$)/);
        if (match) size = Number(match[1]);
      }
    });
    if (!size) return;
    const media = [];
    for (let parent = rule.parent; parent?.type !== 'root'; parent = parent.parent) {
      if (parent.type !== 'atrule' || parent.name !== 'media') throw Error('Review typography context: ' + rule.selector);
      media.unshift(parent.params);
    }
    rules.push({ selectors: rule.selectors, size, media });
  });
  return `// Generated by scripts/generate-monitor-typography.mjs; do not edit manually.\n` +
    `const rules = ${JSON.stringify(rules, null, 2)};\n\n` +
    `export function compatibleBlockTypography(percent: number) {\n` +
    `  const scope = '[data-monitor-font-scale="' + percent + '"]', factor = percent / 100;\n` +
    `  return scope + '{font-size:' + 13 * factor + 'px}' + rules.map(rule => {\n` +
    `    let css = rule.selectors.map(selector => scope + ' ' + selector).join(',') + '{font-size:' + Number((rule.size * factor).toFixed(4)) + 'px}';\n` +
    `    for (const media of [...rule.media].reverse()) css = '@media ' + media + '{' + css + '}';\n` +
    `    return css;\n` +
    `  }).join('');\n}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('../lib/server/monitor-compat/typography.generated.ts', import.meta.url), await generateMonitorTypography());
}
