import { test, expect } from "@playwright/test";
import { infrastructureFixture, signIn } from "../fixtures/infrastructure";

for (const viewport of [{ width: 390, height: 844 }, { width: 1366, height: 768 }]) test(`ASGARD VM name and state filters combine without changing selection or history at ${viewport.width}px`, async ({ page }) => {
  await page.setViewportSize(viewport);
  const state = await infrastructureFixture(page), vms = state.hosts[0].vms;
  vms[0].name = "zeta-technical-worker"; vms[0].displayName = "Worker Principal";
  vms[1].state = "stopped"; vms[2].state = "paused"; vms[3].state = "unknown";
  vms[4].evidence = { ...vms[4].evidence, validUntil: new Date(Date.now() - 60000).toISOString() };
  await signIn(page); await page.goto("/asgard?hostKey=ASGARD");
  const panel = page.locator(".vm-detail-panel"), search = panel.getByRole("searchbox", { name: "Buscar VM", exact: true }), status = panel.getByRole("combobox", { name: "Estado", exact: true });
  const rows = panel.locator("tbody tr");
  await expect(status).toHaveValue("");
  await expect(status.locator("option")).toHaveText(["Todos", "Em execução", "Pausada", "Parada", "Sem estado atual"]);
  await expect(rows).toHaveCount(16);
  await expect(rows.first().getByRole("link", { name: "Worker Principal", exact: true })).toBeVisible();
  await expect.poll(() => state.calls.length).toBe(1);
  await search.fill("  WORKER PRINCIPAL  ");
  await expect(rows).toHaveCount(1);
  await expect(panel.locator(".vm-list-toolbar-count")).toHaveText("1 de 16 VMs");
  await status.selectOption("stopped");
  await expect(panel.getByText("Nenhuma VM corresponde aos filtros.", { exact: true })).toBeVisible();
  await expect(rows).toHaveCount(0);
  await search.fill("");
  await expect(rows).toHaveCount(1);
  await expect(rows.first()).toContainText(vms[1].name);
  await status.selectOption("paused");
  await expect(rows).toHaveCount(1);
  await expect(rows.first()).toContainText(vms[2].name);
  await status.selectOption("unknown");
  await expect(rows).toHaveCount(2);
  await expect(rows.nth(1)).toContainText(vms[4].name);
  await status.selectOption("running");
  await expect(rows).toHaveCount(12);
  await search.fill("TECHNICAL-WORKER");
  await expect(rows).toHaveCount(1);
  await expect(page).toHaveURL(/\/asgard\?hostKey=ASGARD$/);
  expect(state.calls).toHaveLength(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await rows.first().getByRole("link", { name: "Worker Principal", exact: true }).click();
  await expect(page).toHaveURL(/vm=vm-0/);
  await expect(page.getByRole("heading", { name: "Detalhes da VM · Worker Principal", exact: true })).toBeVisible();
  await expect(search).toHaveValue("TECHNICAL-WORKER");
  await expect(status).toHaveValue("running");
  await expect(rows.first()).toHaveClass(/vm-selected/);
  await search.fill(""); await status.selectOption("");
  await expect(rows).toHaveCount(16);
});
